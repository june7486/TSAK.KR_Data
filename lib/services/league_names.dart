    scope == RegionScope.grand ? _kOrderGrand : _kOrderIntegrated;

/// 분류 체계별 매핑 테이블.
Map<String, String> regionMap(RegionScope scope) =>
    scope == RegionScope.grand ? kRegionGrand : kRegionIntegrated;

/// 표시 순서 인덱스(없으면 맨 뒤). 종교 연맹은 순서 목록상 이미 뒤에 있다.
int regionOrderIndex(String region, RegionScope scope) {
  final idx = regionOrder(scope).indexOf(region);
  return idx < 0 ? 9999 : idx;
}

/// 단일 연맹명 → 광역명. 매핑이 없으면 정규화된 원래 이름을 그대로 쓴다.
///   · [scope] = integrated(도·광역시 단위) | grand(인접 광역 통합).
String leagueRegion(
  String? league, {
  RegionScope scope = RegionScope.integrated,
}) {
  final n = normalizeLeague(league);
  if (n.isEmpty) return '';
  return regionMap(scope)[n] ?? n;
}

/// 가나다순 정렬용 비교자.
///  · 종교 연맹(가톨릭 → 원불교 → 기독교)은 지정된 순서대로 **맨 뒤**에 배치한다.
///  · '(미지정)'은 항상 마지막.
///  · 그 외는 한글 음절(U+AC00~U+D7A3) 코드포인트 순서 = 가나다 순서.
int compareLeagueName(String a, String b) {
  const last = '(미지정)';
  // 종교 연맹 후순위(가톨릭 1 → 원불교 2 → 기독교 3), 그 외는 0.
  int relig(String s) => s == '가톨릭'
      ? 1
      : s == '원불교'
      ? 2
      : s == '기독교'
      ? 3
      : 0;
  if (a == last && b != last) return 1;
  if (b == last && a != last) return -1;
  final ra = relig(a), rb = relig(b);
  if (ra != rb) return ra.compareTo(rb);
  return a.compareTo(b);
}
